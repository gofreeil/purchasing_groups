/**
 * מחליף {name} בכיתוב בערכים שהועברו
 * @param {string} s
 * @param {Record<string, string | number>} values
 */
export function fmt(s, values) {
    return s.replace(/\{(\w+)\}/g, (m, k) => (k in values ? String(values[k]) : m));
}
