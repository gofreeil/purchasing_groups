/** ברירת המחדל של הבילדר (ענבר) - לפרסומת בלי גרדיאנט שמור */
export const DEFAULT_AD_GRADIENT = 'linear-gradient(135deg, #f59e0b, #ea580c)';

/** גרדיאנט דו-צבעי פשוט: זווית/כיוון אופציונלי ושני צבעי hex */
const TWO_STOP = /^linear-gradient\(\s*(?:[^,()]+,\s*)?(#[0-9a-f]{3}(?:[0-9a-f]{3})?)\s*,\s*(#[0-9a-f]{3}(?:[0-9a-f]{3})?)\s*\)$/i;

/**
 * הצהרת background לשכבה צבעונית בכרטיס, בכיוון שקהילה בשכונה משתמשת בו.
 * גרדיאנט שאינו דו-צבעי פשוט (למשל שלושה צבעים) נשאר כמו שהוא.
 * @param {string | null | undefined} gradient מחרוזת ה-CSS ששמורה על הפרסומת
 * @param {'to bottom right' | 'to right'} dir br = הרצועה האלכסונית, r = רצועת ה-CTA
 */
export function gradientStyle(gradient, dir) {
    const raw = (gradient ?? '').trim() || DEFAULT_AD_GRADIENT;
    const m = TWO_STOP.exec(raw);
    if (!m) return `background: ${raw};`;
    const [from, to] = [m[1].toLowerCase(), m[2].toLowerCase()];
    const legacy = `background: linear-gradient(${dir}, ${from}, ${to});`;
    return `${legacy} background: linear-gradient(${dir} in oklab, ${TW4[from] ?? from} 0%, ${TW4[to] ?? to} 100%);`;
}
